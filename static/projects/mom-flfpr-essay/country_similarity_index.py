def standardize_country_names(df, country_col):
    df[country_col] = df[country_col].astype(str).str.strip()
    df[country_col] = df[country_col].str.replace(r'^The\s+', '', regex=True).str.replace(r'\s+Republic$', '', regex=True)
    df[country_col] = df[country_col].map(country_mapping).fillna(df[country_col])

    csv_countries = set(df[country_col])
    for country in df[country_col].unique():
        if country in csv_countries:
            continue
        match = process.extractOne(country, csv_countries, scorer=fuzz.token_sort_ratio)
        if match and match[1] > 80:  # Lowered threshold from 90 to 80
            df.loc[df[country_col] == country, country_col] = match[0]

    return df

def analyze_flpr_trends(flpr_data, singapore_flpr=64.409, min_data_points=3):
    print("\n=== STEP 1: FLPR TREND ANALYSIS ===")
    flpr_data = standardize_country_names(flpr_data, 'Country')
    flpr_cols = [col for col in flpr_data.columns if 'Labor force participation rate, female' in col]
    flpr_cols.sort()

    for col in flpr_cols:
        flpr_data[col] = pd.to_numeric(flpr_data[col], errors='coerce')

    qualified_countries = []
    trend_analysis = []

    for _, row in flpr_data.iterrows():
        country = row['Country']
        values = [row[col] for col in flpr_cols]
        valid_values = [(i, v) for i, v in enumerate(values) if pd.notna(v)]

        if len(valid_values) < min_data_points:
            continue

        just_values = [v[1] for v in valid_values]
        start_flpr = just_values[0]
        end_flpr = just_values[-1]
        total_change = end_flpr - start_flpr
        changes = np.diff(just_values)
        avg_yoy_change = np.mean(changes) if len(changes) > 0 else 0
        flpr_std = np.std(just_values)
        cv = flpr_std / np.mean(just_values) if np.mean(just_values) > 0 else float('inf')

        is_qualified = False
        reason = ""
        confidence = 0

        # Consistent: FLPR > Singapore’s max (64.409%) in 2024, low variability
        if end_flpr > singapore_flpr and cv < 0.1:
            is_qualified = True
            reason = f"Consistent high FLPR ({end_flpr:.1f}% in 2024, CV: {cv:.3f})"
            confidence = 0.9
        # Increasing: Total change > 10% or avg YoY > 2%
        elif total_change > 10 or (avg_yoy_change > 2 and len(changes) > 0):
            is_qualified = True
            reason = f"Major FLPR increase (+{total_change:.1f}% total, {avg_yoy_change:.1f}% avg YoY)"
            confidence = 0.8

        if is_qualified:
            qualified_countries.append(country)

        trend_analysis.append({
            'Country': country,
            'Latest_FLPR': end_flpr,
            'Total_Change': total_change,
            'Avg_YoY_Change': avg_yoy_change,
            'Coefficient_of_Variation': cv,
            'Data_Points': len(valid_values),
            'Qualified': is_qualified,
            'Qualification_Reason': reason,
            'Confidence_Score': confidence
        })

    trend_df = pd.DataFrame(trend_analysis)
    qualified_df = trend_df[trend_df['Qualified'] == True].copy()

    print(f"Total countries analyzed: {len(trend_df)}")
    print(f"Qualified countries: {len(qualified_df)}")
    print("\nTop 10 Qualified Countries:")
    print(qualified_df.nlargest(10, 'Confidence_Score')[['Country', 'Latest_FLPR', 'Total_Change', 'Confidence_Score', 'Qualification_Reason']].to_string(index=False))

    return qualified_countries, trend_df, qualified_df

def impute_missing_data(combined_data, global_data):
    print("\n=== Imputing Missing Data ===")
    metrics = ['Avg. Work Hours (Females)', 'Cost Index', 'Purchasing Power Index', 'GDP per capita']
    skipped_countries = []

    # Pre-clean global_data: Drop rows with all NaN in relevant metrics
    global_data_clean = global_data.dropna(subset=metrics, how='all')
    print(f"Global data after cleaning: {len(global_data_clean)} countries (dropped {len(global_data) - len(global_data_clean)} with all NaN metrics)")

    for idx, row in combined_data[combined_data[metrics].isna().any(axis=1)].iterrows():
        country = row['Country']
        valid_metrics = row[metrics].notna()
        valid_data = [col for col in metrics if valid_metrics[col]]

        if not valid_data:
            print(f"Skipping {country}: No valid metrics for imputation.")
            skipped_countries.append(country)
            continue

        # Normalize available metrics
        norm_data = global_data_clean.copy()
        for col in valid_data:
            col_data = norm_data[col]
            if col_data.isna().all():
                print(f"Skipping {country}: All values for {col} are NaN in global_data_clean.")
                skipped_countries.append(country)
                break
            norm_data[col] = (col_data - col_data.min()) / (col_data.max() - col_data.min() + 1e-10)

        if country in skipped_countries:
            continue

        # Get country vector
        country_vec = norm_data[norm_data['country'] == country][valid_data].values
        if len(country_vec) == 0 or np.any(np.isnan(country_vec)):
            print(f"Skipping {country}: Invalid vector after normalization (NaN values or not found).")
            skipped_countries.append(country)
            continue

        # Get comparison countries
        other_countries = norm_data[norm_data['country'] != country][valid_data]
        if other_countries.empty or other_countries.isna().all().all():
            print(f"Skipping {country}: No valid comparison countries.")
            skipped_countries.append(country)
            continue

        # Remove NaN rows from other_countries
        other_countries_clean = other_countries.dropna()
        if other_countries_clean.empty:
            print(f"Skipping {country}: No valid comparison countries after removing NaN.")
            skipped_countries.append(country)
            continue

        # Get corresponding country names for valid rows
        valid_indices = other_countries.dropna().index
        valid_countries = norm_data.loc[valid_indices, 'country']

        # Calculate distances
        distances = euclidean_distances(country_vec, other_countries_clean.values).flatten()
        if len(distances) == 0:
            print(f"Skipping {country}: No valid distances calculated.")
            skipped_countries.append(country)
            continue

        closest_idx = np.argmin(distances)
        closest_country = valid_countries.iloc[closest_idx]

        for col in metrics:
            if pd.isna(row[col]):
                value = global_data[global_data['country'] == closest_country][col].iloc[0]
                if pd.isna(value):
                    # Fallback to median if closest country's value is NaN
                    value = combined_data[col].median()
                    print(f"Imputed {col} for {country} using median (closest country {closest_country} had NaN): {value}")
                else:
                    print(f"Imputed {col} for {country} using {closest_country}: {value}")
                combined_data.loc[idx, col] = value

    # Fallback: Impute remaining NaNs with median
    for col in metrics:
        if combined_data[col].isna().any():
            median_value = combined_data[col].median()
            if pd.isna(median_value):
                print(f"Warning: Median for {col} is NaN, using global_data_clean median.")
                median_value = global_data_clean[col].median()
            combined_data[col] = combined_data[col].fillna(median_value)
            print(f"Imputed remaining NaNs in {col} with median: {median_value}")

    # Impute missing Comprehensive_Similarity_Index
    if combined_data['Comprehensive_Similarity_Index'].isna().any():
        median_value = combined_data['Comprehensive_Similarity_Index'].median()
        if pd.isna(median_value):
            print("Warning: Median for Comprehensive_Similarity_Index is NaN, using 50 as default.")
            print("Check 'Countries Similarity Index.xlsx' for missing or incorrect 'Similarity Index' column.")
            median_value = 50.0
        combined_data['Comprehensive_Similarity_Index'] = combined_data['Comprehensive_Similarity_Index'].fillna(median_value)
        print(f"Imputed Comprehensive_Similarity_Index with median: {median_value}")

    if skipped_countries:
        print(f"Skipped countries due to insufficient data: {', '.join(skipped_countries)}")

    return combined_data

def calculate_similarity_index(global_data, similarity_index, qualified_df, singapore_metrics):
    print("\n=== STEP 2: NEW SIMILARITY INDEX ===")
    global_data = standardize_country_names(global_data, 'country')
    similarity_index = standardize_country_names(similarity_index, 'PLACE')

    for col in ['Avg. Work Hours (Females)', 'Cost Index', 'Purchasing Power Index', 'GDP per capita']:
        global_data[col] = pd.to_numeric(global_data[col], errors='coerce')

    # Check for NaN in Similarity Index and verify column
    if 'Similarity Index' not in similarity_index.columns:
        print("Error: 'Similarity Index' column not found in Countries Similarity Index.xlsx.")
        print(f"Available columns: {list(similarity_index.columns)}")
        print("Please verify the column name and update the script or Excel file.")
    else:
        nan_sim_count = similarity_index['Similarity Index'].isna().sum()
        print(f"Similarity Index NaN count: {nan_sim_count} out of {len(similarity_index)} countries")
        if nan_sim_count == len(similarity_index):
            print("Warning: All Similarity Index values are NaN. Ranking will rely on New_Similarity_Score.")

    # Merge with qualified countries
    combined_data = qualified_df[['Country', 'Latest_FLPR', 'Confidence_Score']].merge(
        global_data[['country', 'Avg. Work Hours (Females)', 'Cost Index', 'Purchasing Power Index', 'GDP per capita']],
        left_on='Country', right_on='country', how='inner'
    ).merge(
        similarity_index[['PLACE', 'Similarity Index']], left_on='Country', right_on='PLACE', how='left'
    )

    combined_data.drop(['country', 'PLACE'], axis=1, inplace=True, errors='ignore')
    combined_data.rename(columns={'Similarity Index': 'Comprehensive_Similarity_Index'}, inplace=True)

    print(f"Combined data before imputation: {len(combined_data)} countries")

    # Impute missing data
    combined_data = impute_missing_data(combined_data, global_data)

    print(f"Combined data after imputation: {len(combined_data)} countries")

    # Calculate correlations
    metrics = ['Avg. Work Hours (Females)', 'Cost Index', 'Purchasing Power Index', 'GDP per capita']
    correlations = {}
    for metric in metrics:
        valid_data = combined_data[[metric, 'Latest_FLPR']].dropna()
        if len(valid_data) > 1:
            corr, _ = pearsonr(valid_data[metric], valid_data['Latest_FLPR'])
            correlations[metric] = abs(corr)
        else:
            correlations[metric] = 0.0

    total_corr = sum(correlations.values()) + 1e-10
    weights = {metric: corr / total_corr for metric, corr in correlations.items()}
    weights['Latest_FLPR'] = max(weights.values()) * 1.5
    weights['Comprehensive_Similarity_Index'] = 0.2
    total_weight = sum(weights.values())
    weights = {k: v / total_weight for k, v in weights.items()}

    print("\nCorrelation Coefficients with FLPR:")
    for metric, corr in correlations.items():
        print(f"{metric}: {corr:.3f}")
    print("\nWeights:")
    for metric, weight in weights.items():
        print(f"{metric}: {weight:.3f}")

    # Calculate normalized differences
    combined_data['flpr_diff'] = abs(combined_data['Latest_FLPR'] - singapore_metrics['Latest_FLPR']) / singapore_metrics['Latest_FLPR']
    combined_data['hours_diff'] = abs(combined_data['Avg. Work Hours (Females)'] - singapore_metrics['Avg. Work Hours (Females)']) / singapore_metrics['Avg. Work Hours (Females)']
    combined_data['gdp_diff'] = abs(combined_data['GDP per capita'] - singapore_metrics['GDP per capita']) / singapore_metrics['GDP per capita']
    combined_data['ppi_diff'] = abs(combined_data['Purchasing Power Index'] - singapore_metrics['Purchasing Power Index']) / singapore_metrics['Purchasing Power Index']
    combined_data['ci_diff'] = abs(combined_data['Cost Index'] - singapore_metrics['Cost Index']) / singapore_metrics['Cost Index']

    comp_sim = combined_data['Comprehensive_Similarity_Index']
    combined_data['comp_sim_diff'] = 1 - (comp_sim - comp_sim.min()) / (comp_sim.max() - comp_sim.min() + 1e-10)

    combined_data['New_Similarity_Score'] = (
        weights['Latest_FLPR'] * combined_data['flpr_diff'] +
        weights['Avg. Work Hours (Females)'] * combined_data['hours_diff'] +
        weights['GDP per capita'] * combined_data['gdp_diff'] +
        weights['Purchasing Power Index'] * combined_data['ppi_diff'] +
        weights['Cost Index'] * combined_data['ci_diff'] +
        weights['Comprehensive_Similarity_Index'] * combined_data['comp_sim_diff']
    )

    return combined_data

def rank_countries(combined_data, singapore_metrics, flpr_data):
    print("\n=== STEP 3: FINAL RANKING ===")
    # Rank by Comprehensive Similarity Index (primary) and New_Similarity_Score (secondary, lower is better)
    final_ranking = combined_data.sort_values(['Comprehensive_Similarity_Index', 'New_Similarity_Score'], ascending=[False, True]).head(10)

    print("\nTop 10 Countries Ranked by Comprehensive Similarity Index (with New_Similarity_Score as tiebreaker):")
    print(final_ranking[['Country', 'Avg. Work Hours (Females)', 'Latest_FLPR', 'GDP per capita',
                        'Purchasing Power Index', 'Cost Index', 'Comprehensive_Similarity_Index',
                        'New_Similarity_Score']].to_string(index=False))

    print("\nPolicy Explanations:")
    for _, row in final_ranking.iterrows():
        print(f"\n{row['Country']}:")
        print(f"- Avg. Work Hours (Females): {row['Avg. Work Hours (Females)']:.1f}")
        print(f"- FLPR (2024): {row['Latest_FLPR']:.1f}%")
        print(f"- GDP per Capita: ${row['GDP per capita']:.2f}")
        print(f"- PPI: {row['Purchasing Power Index']:.1f}")
        print(f"- Cost Index: {row['Cost Index']:.1f}")
        print(f"- Comprehensive Similarity: {row['Comprehensive_Similarity_Index']:.1f}")
        print(f"- New Similarity Score: {row['New_Similarity_Score']:.3f} (lower is closer to Singapore)")
        print(f"- Policy Relevance: {'High FLPR and economic similarity make it ideal for policy analysis.' if row['Latest_FLPR'] > singapore_metrics['Latest_FLPR'] else 'Strong FLPR growth and economic similarity, relevant for policy comparison.'}")

    # Missing data
    all_countries = set(str(x) for x in flpr_data['Country'] if pd.notna(x))
    filtered_countries = set(combined_data['Country'])
    missing_countries = all_countries - filtered_countries
    if missing_countries:
        print("\nExcluded Countries (Missing FLPR or Merge Failure):")
        print(", ".join(sorted(missing_countries)))
        print("Consider sourcing data from ILOSTAT or other reliable sources.")

def main():
    print("=== SINGAPORE FLPR POLICY ANALYSIS ===")
    global_data, similarity_index, flpr_data = load_data()
    if global_data is None:
        return

    # Singapore’s metrics
    singapore_row = flpr_data[flpr_data['Country'] == 'Singapore']
    singapore_metrics = {
        'Latest_FLPR': singapore_row['Labor force participation rate, female 2024'].iloc[0] if not singapore_row.empty else 62.349,
        'Avg. Work Hours (Females)': global_data[global_data['country'] == 'Singapore']['Avg. Work Hours (Females)'].iloc[0] if not global_data[global_data['country'] == 'Singapore'].empty else 40.0,
        'GDP per capita': 89369.72,
        'Purchasing Power Index': 112.5,
        'Cost Index': 78.0
    }

    # Step 1: FLPR trend analysis
    qualified_countries, trend_df, qualified_df = analyze_flpr_trends(flpr_data)

    if len(qualified_df) == 0:
        print("No countries qualified!")
        return

    # Step 2: Calculate new similarity index
    combined_data = calculate_similarity_index(global_data, similarity_index, qualified_df, singapore_metrics)

    # Step 3: Rank countries
    rank_countries(combined_data, singapore_metrics, flpr_data)

if __name__ == "__main__":
    main()



